/**
 * Build step: writes sw.js, the service worker that lets unidash open without a connection.
 * It saves the app's own files (HTML, scripts, styles, fonts, icons) when it installs. Pages are fetched
 * fresh when online (3 s limit, then the saved copy), files with a content hash in their name come
 * from the saved copy. Each build has its own cache, so a new deploy replaces the old one.
 * Other sites (weather, Google) are never touched: they stay live-only.
 */
import type { Plugin } from 'vite'

// Language files load only when that language is picked; the worker saves them the first time they're used.
const LOCALE = /^assets\/(el|es|fr|de|it|pt|ru|tr|zh|ja|ko|hi|id|ar|ur)-[\w-]+\.js$/
const PUBLIC = ['./', 'privacy.html', 'manifest.webmanifest', 'favicon.svg', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png']

const worker = (version: string, files: string[]) => `// unidash service worker, build ${version}. Generated by build/serviceWorker.ts.
const CACHE = 'unidash-${version}'
const PRECACHE = ${JSON.stringify(files)}
const SKIP = /(version\\.json|app-bundle\\.zip)$/

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('unidash-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin || SKIP.test(url.pathname)) return
  event.respondWith(request.mode === 'navigate' ? page(request) : file(request))
})

/** Pages: the live version when it arrives within 3 s (and save it), otherwise the saved one. */
async function page(request) {
  const cache = await caches.open(CACHE)
  const live = fetch(request).then((response) => {
    if (response.ok) cache.put(request, response.clone())
    return response
  })
  const slow = new Promise((resolve) => setTimeout(resolve, 3000))
  try {
    const first = await Promise.race([live, slow])
    if (first) return first
  } catch {
    // Offline: use the saved page below.
  }
  const saved = (await cache.match(request, { ignoreSearch: true, ignoreVary: true })) || (await cache.match('./', { ignoreVary: true }))
  return saved || live
}

/** Files: the saved copy, else fetch and save it. */
async function file(request) {
  const cache = await caches.open(CACHE)
  const saved = await cache.match(request, { ignoreVary: true })
  if (saved) return saved
  const response = await fetch(request)
  if (response.ok && response.type === 'basic') cache.put(request, response.clone())
  return response
}
`

export function serviceWorker(version: string): Plugin {
  return {
    name: 'unidash-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && !LOCALE.test(f))
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker(version, [...PUBLIC, ...files]) })
    },
  }
}
